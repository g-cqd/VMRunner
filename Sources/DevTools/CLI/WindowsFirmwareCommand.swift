import ArgumentParser
import Foundation

/// Offline, reproducible build of our own firmware, never Windows or a third-party boot implementation.
struct WindowsFirmwareCommand: AsyncParsableCommand {
    static let configuration = CommandConfiguration(
        commandName: "firmware", abstract: "Rebuilds and verifies the embedded Windows framebuffer bootstrap (no VM, no network).")

    @OptionGroup var project: ProjectOptions
    @Flag(help: "Update the generated Swift firmware bytes after a reviewed C source change.") var update = false

    func run() async throws {
        try await perform {
            let root = try project.packageRoot()
            let folder = root.appending(path: "Firmware/WindowsBoot")
            try verifyHeaders(in: folder)
            let scratch = FileManager.default.temporaryDirectory.appending(path: "vmr-firmware-\(UUID())")
            try FileManager.default.createDirectory(at: scratch, withIntermediateDirectories: false)
            defer { try? FileManager.default.removeItem(at: scratch) }
            let object = scratch.appending(path: "boot.obj")
            let binary = scratch.appending(path: "BOOTAA64.EFI")
            let compile = try await ProcessRunner.run(
                CommandSpec(
                    executable: "/usr/bin/clang",
                    arguments: [
                        "-x", "c", "-target", "aarch64-unknown-windows", "-ffreestanding", "-fshort-wchar", "-fno-builtin",
                        "-fno-stack-protector", "-mno-implicit-float", "-O2", "-Wall", "-Wextra", "-Werror",
                        "-I", folder.appending(path: "Include").path, "-I", folder.appending(path: "Include/AArch64").path,
                        "-c", folder.appending(path: "FramebufferBoot.c").path, "-o", object.path,
                    ]))
            guard compile.succeeded else { throw ToolError(compile.standardError) }
            let link = try await ProcessRunner.run(
                CommandSpec(
                    executable: "lld-link",
                    arguments: [
                        "/nologo", "/Brepro", "/nodefaultlib", "/dll", "/entry:efi_main", "/subsystem:efi_application",
                        "/out:\(binary.path)", object.path,
                    ]))
            guard link.succeeded else { throw ToolError(link.standardError) }
            let bytes = try Data(contentsOf: binary).base64EncodedString()
            let lines = stride(from: 0, to: bytes.count, by: 96).map { offset in
                "        " + String(bytes.dropFirst(offset).prefix(96))
            }.joined(separator: "\n")
            let digest = try FileDigest.sha256(ofFileAt: binary)
            let sourceDigest = try FileDigest.sha256(ofFileAt: folder.appending(path: "FramebufferBoot.c"))
            let quotes = String(repeating: "\"", count: 3)
            let generated = """
                // Generated by `vmr windows firmware --update`; review Firmware/WindowsBoot/FramebufferBoot.c instead.
                enum WindowsBootFirmwareData {
                    static let sha256 = "\(digest)"
                    static let sourceSHA256 = "\(sourceDigest)"
                    static let base64 = \(quotes)
                \(lines)
                        \(quotes)
                }

                """
            let destination = root.appending(path: "Sources/VMRunner/Engine/Windows/WindowsBootFirmwareData.swift")
            if update {
                try FileManager.default.createDirectory(at: destination.deletingLastPathComponent(), withIntermediateDirectories: true)
                try generated.write(to: destination, atomically: true, encoding: .utf8)
            } else {
                guard try String(contentsOf: destination, encoding: .utf8) == generated else {
                    throw ToolError("embedded firmware differs; review the source, then run vmr windows firmware --update")
                }
            }
            Output.out("Windows bootstrap SHA-256: \(digest) (headers verified, no guest started)")
            return 0
        }
    }

    private func verifyHeaders(in folder: URL) throws {
        let manifest = try String(contentsOf: folder.appending(path: "headers.sha256"), encoding: .utf8)
        for line in manifest.split(separator: "\n") {
            let fields = line.split(separator: " ", omittingEmptySubsequences: true)
            guard fields.count == 2, !fields[1].contains(".."), !fields[1].hasPrefix("/"),
                try FileDigest.sha256(ofFileAt: folder.appending(path: "Include/\(fields[1])")) == fields[0]
            else { throw ToolError("pinned UEFI header checksum mismatch: \(line)") }
        }
    }
}
