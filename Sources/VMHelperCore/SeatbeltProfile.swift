/// Generates the Seatbelt profile (SBPL, the language `sandbox-exec -f` reads) a helper runs under.
///
/// The profile denies everything, then allows: the loader's bootstrap (Apple's `dyld-support.sb`), the helper's own
/// executable, the system files and services the framework was observed to need, the files the descriptor names, and, only
/// when the grants ask for host sockets, outbound sockets and the name resolver. Nothing in the output is copied from the
/// descriptor except paths, and a path is checked (`SandboxPath`) and written inside a quoted string only.
///
/// SBPL is not documented for third parties and Apple's profiles are private and subject to change; every rule below was
/// found by running the helper under a deny-default profile and reading the denials (see the research note).
public enum SeatbeltProfile {
    /// Reads the helper and the framework need: the system volume (frameworks, the dyld shared cache, resources), the C
    /// library, ICU data, and the global preferences file Foundation reads when it starts.
    static let systemReads = [
        #"(subpath "/System")"#,
        #"(subpath "/usr/lib")"#,
        #"(subpath "/usr/share/icu")"#,
        #"(literal "/Library/Preferences/.GlobalPreferences.plist")"#,
    ]

    /// Links in the root that programs name paths through (`/etc/hosts`, `/tmp/x`); a lookup stats them before it follows them.
    static let systemMetadata = ["/etc", "/tmp", "/var"]

    /// Kernel values the framework reads. `hw.pagesize_compat` was found by a boot: with it denied (log line `Sandbox:
    /// VMHelper(pid) deny(1) sysctl-read hw.pagesize_compat`) the start fails with "The boot loader is invalid", and
    /// allowing it alone is what lets the machine start.
    static let sysctls = [
        "hw.ephemeral_storage", "hw.memsize", "hw.pagesize_compat", "kern.bootargs", "kern.hv_support", "kern.iossupportversion",
        "kern.maxfilesperproc", "kern.osproductversion", "kern.osvariant_status", "security.mac.lockdown_mode_state",
    ]

    /// Mach services the helper looks up before it starts a machine: logging, notifications, and the disk-image service the
    /// framework asks to validate an image.
    static let machServices = ["com.apple.diskimagescontroller", "com.apple.logd", "com.apple.system.notification_center"]

    /// Mach services the per-machine service is reached through. Verified by a boot: without it the start fails with
    /// "Internal Virtualization error. The virtual machine failed to start." and the log shows `deny(1) mach-lookup
    /// com.apple.Virtualization.VirtualMachine (xpc)`.
    static let virtualizationServices = ["com.apple.Virtualization.VirtualMachine"]

    /// The profile text for `grants`. `helperExecutable` is the canonical path of the helper binary, which `sandbox-exec`
    /// executes under the profile. A path that is not plain (see `SandboxPath`) is refused, whoever validated it before.
    public static func generate(grants: SandboxGrants, helperExecutable: String) throws -> String {
        for path in [helperExecutable] + grants.read + grants.readWrite + [grants.consoleSocket].compactMap(\.self) {
            try SandboxPath.validate(path)
        }
        var lines = [
            "(version 1)",
            ";; Generated by `vmr sandbox`: deny by default, then only what the helper and its descriptor need.",
            "(deny default)",
            #"(import "dyld-support.sb")"#,
            "",
            ";; The helper itself.",
            "(allow process-exec \(literal(helperExecutable)))",
            "(allow file-read* \(literal(helperExecutable)))",
            "",
            ";; System files, system services and kernel values the framework needs to start.",
            "(allow file-read* \(systemReads.joined(separator: " ")))",
            "(allow sysctl-read \(sysctls.map { #"(sysctl-name "\#($0)")"# }.joined(separator: " ")))",
            "(allow mach-lookup \((machServices + virtualizationServices).map { #"(global-name "\#($0)")"# }.joined(separator: " ")))",
            #"(allow ipc-posix-shm-read-data (ipc-posix-name "apple.shm.notification_center"))"#,
            "",
            ";; Directories on the way to the granted files may be looked at, nothing more.",
        ]
        let reached = [helperExecutable] + grants.read + grants.readWrite + [grants.consoleSocket].compactMap(\.self)
        let ancestors = Set(reached.flatMap(Self.ancestors) + systemMetadata)
        lines += ancestors.sorted().map { "(allow file-read-metadata \(literal($0)))" }

        lines += ["", ";; Files the descriptor names. The framework hands them on to the per-machine service as sandbox extensions."]
        for path in grants.read {
            lines.append("(allow file-read* \(literal(path)))")
            lines.append(issueExtension("com.apple.app-sandbox.read", path))
        }
        for path in grants.readWrite {
            lines.append("(allow file-read* file-write* \(literal(path)))")
            lines.append(issueExtension("com.apple.app-sandbox.read", path))
            lines.append(issueExtension("com.apple.app-sandbox.read-write", path))
        }

        if let socket = grants.consoleSocket {
            lines += [
                "",
                ";; The console socket: the helper creates it, listens on it and removes it. Clients connect from outside.",
                "(allow file-read-metadata file-write* \(literal(socket)))",
                "(allow network-bind (local unix-socket (path-literal \"\(socket)\")))",
                "(allow network-inbound (local unix-socket (path-literal \"\(socket)\")))",
            ]
        }

        if grants.hostSockets {
            lines += [
                "",
                ";; Host sockets for a network the helper hosts: connect anywhere, resolve names through mDNSResponder. No bind.",
                #"(allow network-outbound (remote ip "*:*") (literal "/private/var/run/mDNSResponder"))"#,
                #"(allow file-read* (literal "/private/etc/hosts") (literal "/Library/Preferences/com.apple.networkd.plist"))"#,
                #"(allow sysctl-read (sysctl-name-prefix "net.routetable."))"#,
            ]
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// A path as an SBPL `literal` filter. The path was validated: it holds no quote, backslash or control character.
    static func literal(_ path: String) -> String {
        "(literal \"\(path)\")"
    }

    private static func issueExtension(_ extensionClass: String, _ path: String) -> String {
        "(allow file-issue-extension (require-all (extension-class \"\(extensionClass)\") \(literal(path))))"
    }

    /// `/a/b/c` gives `/a` and `/a/b`.
    static func ancestors(of path: String) -> [String] {
        let components = path.split(separator: "/").dropLast()
        return (0..<components.count).map { "/" + components.prefix($0 + 1).joined(separator: "/") }
    }
}
